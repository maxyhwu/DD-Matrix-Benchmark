import cudaq
cudaq.set_target('tensornet')
@cudaq.kernel
def circuit():
    q = cudaq.qvector(4)
    x(q[3])
    z(q[3])
    x(q[1])
    h(q[3])
    rz(-1.5707963267948966, q[3])
    h(q[3])
    h(q[2])
    x.ctrl([q[2]], q[3])
    h(q[2])
    rz(-1.5707963267948966, q[2])
    x.ctrl([q[3]], q[2])
    swap(q[3], q[2])
    h(q[1])
    rz(-1.5707963267948966, q[1])
    h(q[1])
    rz(-1.5707963267948966, q[1])
    swap(q[2], q[1])
    h(q[0])
    x.ctrl([q[0]], q[2])
    x.ctrl([q[0]], q[1])
    h(q[0])
    x.ctrl([q[3]], q[0])
    x.ctrl([q[2]], q[0])
    rz(-1.5707963267948966, q[0])
    x.ctrl([q[1]], q[0])

counts = cudaq.sample(circuit, shots_count=1024)
print(counts)