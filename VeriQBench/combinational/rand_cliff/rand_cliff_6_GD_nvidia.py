import cudaq
cudaq.set_target('nvidia')
@cudaq.kernel
def circuit():
    q = cudaq.qvector(6)
    s(q[0])
    h(q[0])
    s(q[1])
    h(q[3])
    s(q[4])
    swap(q[5], q[0])
    x.ctrl([q[5]], q[1])
    x.ctrl([q[5]], q[3])
    x.ctrl([q[4]], q[2])
    x.ctrl([q[2]], q[5])
    x.ctrl([q[5]], q[4])
    s(q[0])
    h(q[0])
    h(q[1])
    h(q[2])
    h(q[4])
    swap(q[1], q[0])
    x.ctrl([q[3]], q[1])
    x.ctrl([q[0]], q[1])
    x.ctrl([q[2]], q[4])
    x.ctrl([q[1]], q[2])
    h(q[2])
    x.ctrl([q[2]], q[1])
    s(q[0])
    s(q[3])
    s(q[4])
    swap(q[3], q[0])
    x.ctrl([q[3]], q[2])
    x.ctrl([q[3]], q[0])
    x.ctrl([q[3]], q[4])
    h(q[4])
    x.ctrl([q[4]], q[3])
    h(q[0])
    h(q[2])
    s(q[4])
    h(q[4])
    swap(q[2], q[0])
    x.ctrl([q[4]], q[2])
    x.ctrl([q[2]], q[0])
    h(q[0])
    x.ctrl([q[0]], q[2])
    s(q[0])
    h(q[0])
    s(q[4])
    h(q[4])
    x.ctrl([q[4]], q[0])
    x(q[1])
    y(q[2])
    x(q[3])
    x(q[4])
    z(q[5])

counts = cudaq.sample(circuit, shots_count=1024)
print(counts)