import cudaq
cudaq.set_target('tensornet')
@cudaq.kernel
def circuit():
    q = cudaq.qvector(5)
    s(q[0])
    h(q[0])
    s(q[0])
    s(q[1])
    s(q[2])
    s(q[4])
    swap(q[3], q[0])
    x.ctrl([q[3]], q[4])
    x.ctrl([q[2]], q[1])
    x.ctrl([q[1]], q[3])
    x.ctrl([q[3]], q[2])
    h(q[0])
    h(q[1])
    h(q[2])
    s(q[2])
    x.ctrl([q[0]], q[4])
    x.ctrl([q[2]], q[1])
    x.ctrl([q[1]], q[0])
    x.ctrl([q[0]], q[2])
    s(q[1])
    h(q[1])
    h(q[2])
    swap(q[2], q[1])
    x.ctrl([q[2]], q[1])
    h(q[1])
    x.ctrl([q[1]], q[2])
    h(q[1])
    s(q[1])
    swap(q[4], q[1])
    x.ctrl([q[4]], q[1])
    s(q[1])
    y(q[0])
    y(q[1])
    y(q[2])
    y(q[3])
    z(q[4])

counts = cudaq.sample(circuit, shots_count=1024)
print(counts)