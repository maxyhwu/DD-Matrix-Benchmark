    x.ctrl([q[0]], q[1])
    h(q[1])
    x.ctrl([q[1]], q[0])
    x.ctrl([q[6]], q[2])
    x.ctrl([q[2]], q[0])
    x.ctrl([q[0]], q[6])
    s(q[1])
    h(q[1])
    s(q[1])
    s(q[4])
