    x.ctrl([q[6]], q[2])
    x.ctrl([q[2]], q[3])
    x.ctrl([q[3]], q[6])
    h(q[0])
    s(q[0])
    h(q[1])
    s(q[2])
    h(q[2])
    h(q[5])
    h(q[6])
    s(q[6])
    x.ctrl([q[4]], q[0])
