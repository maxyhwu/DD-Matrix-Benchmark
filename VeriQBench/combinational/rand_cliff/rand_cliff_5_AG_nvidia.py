import cudaq
cudaq.set_target('nvidia')
@cudaq.kernel
def circuit():
    q = cudaq.qvector(5)
    x(q[4])
    x(q[2])
    x(q[1])
    h(q[4])
    rz(-1.5707963267948966, q[4])
    h(q[4])
    rz(-1.5707963267948966, q[4])
    h(q[3])
    rz(-1.5707963267948966, q[3])
    h(q[3])
    rz(-1.5707963267948966, q[3])
    x.ctrl([q[4]], q[3])
    rz(-1.5707963267948966, q[3])
    x.ctrl([q[3]], q[4])
    h(q[2])
    rz(-1.5707963267948966, q[2])
    x.ctrl([q[2]], q[4])
    x.ctrl([q[2]], q[3])
    h(q[2])
    swap(q[3], q[2])
    h(q[1])
    x.ctrl([q[1]], q[2])
    h(q[1])
    x.ctrl([q[4]], q[1])
    x.ctrl([q[3]], q[1])
    x.ctrl([q[2]], q[1])
    rz(-1.5707963267948966, q[1])
    x.ctrl([q[4]], q[1])
    x.ctrl([q[2]], q[1])
    h(q[0])
    x.ctrl([q[0]], q[4])
    x.ctrl([q[0]], q[3])
    x.ctrl([q[0]], q[1])
    h(q[0])
    x.ctrl([q[4]], q[0])
    x.ctrl([q[3]], q[0])
    x.ctrl([q[1]], q[0])
    rz(-1.5707963267948966, q[0])
    x.ctrl([q[4]], q[0])
    x.ctrl([q[3]], q[0])
    x.ctrl([q[0]], q[4])
    swap(q[3], q[0])

counts = cudaq.sample(circuit, shots_count=1024)
print(counts)